import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('qa',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const checks=[], errors=[], writes=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.url().includes('/api/')&&r.method()!=='GET')writes.push(r.method());});
 const base='http://127.0.0.1:5173';
 await page.goto(`${base}/studio/Experiment`);
 await page.getByRole('heading',{name:'模拟日历'}).waitFor();
 await page.locator('canvas').waitFor();
 const initial=await page.locator('.update-time').textContent();
 await page.waitForFunction(value=>document.querySelector('.update-time')?.textContent!==value,initial,{timeout:12000});
 checks.push('5-second polling updates observation timestamp');
 await page.getByRole('button',{name:'每 5 秒读取'}).click();
 await page.waitForTimeout(700);
 const paused=await page.locator('.update-time').textContent();
 await page.waitForTimeout(5500);
 assert.equal(await page.locator('.update-time').textContent(),paused);
 checks.push('pause stops automatic reads');
 await page.getByRole('button',{name:'紧凑',exact:true}).click();
 assert.ok(await page.locator('.app.compact').count());
 await page.screenshot({path:'qa/experiment-compact.png',fullPage:true});
 await page.getByRole('button',{name:'舒适',exact:true}).click();
 await page.screenshot({path:'qa/experiment-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'查看数据',exact:true}).click();
 assert.ok(await page.locator('tbody tr').count()>10);
 await page.getByRole('button',{name:'查看曲线'}).click();
 await page.getByLabel('选择资产').selectOption('TTEI');
 await page.waitForFunction(()=>document.querySelector('select[aria-label="选择资产"]')?.value==='TTEI');
 checks.push('density and chart/table/asset switching');
 await page.getByRole('tab',{name:'Agent 快照'}).click();
 await page.locator('tbody tr').first().waitFor();
 const original=await page.locator('tbody tr td').first().textContent();
 await page.getByRole('button',{name:'下一页',exact:true}).click();
 await page.waitForFunction(id=>document.querySelector('tbody tr td')?.textContent!==id,original);
 await page.locator('tbody .text-link').first().click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('heading',{name:'当前持仓'}).waitFor();
 await page.screenshot({path:'qa/agent-inspector.png'});
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0);
 await page.getByLabel('搜索成员').fill('NO_SUCH_AGENT_12345');
 await page.getByText('没有匹配的成员').waitFor();
 checks.push('server pagination, detail drawer, Escape and empty search');
 await page.locator('.sidebar a[href="/studio/Agent"]').click();
 await page.getByRole('heading',{name:'成员档案'}).waitFor();
 await page.locator('tbody tr').first().waitFor();
 await page.screenshot({path:'qa/agent-desktop.png',fullPage:true});
 await page.getByRole('button',{name:/查看测试规划/}).click();
 await page.getByRole('dialog').waitFor();
 await page.getByText('规划入口 · 不执行操作').waitFor();
 await page.keyboard.press('Escape');
 await page.locator('.sidebar a[href="/studio/Market"]').click();
 await page.locator('canvas').waitFor();
 await page.screenshot({path:'qa/market-desktop.png',fullPage:true});
 await page.getByRole('tab',{name:'资产组合包'}).click();
 assert.equal(await page.locator('tbody tr').count(),10);
 await page.getByRole('tab',{name:'数据工作台'}).click();
 assert.equal(await page.locator('tbody tr').count(),4);
 await page.locator('.sidebar a[href="/studio/Setting"]').click();
 await page.getByRole('heading',{name:'模型连接',exact:true}).waitFor();
 await page.screenshot({path:'qa/setting-desktop.png',fullPage:true});
 await page.reload();
 await page.getByRole('heading',{name:'模型连接',exact:true}).waitFor();
 checks.push('four routes, planned-only workflows, market inventory, deep-link reload');
 await page.goBack();
 await page.getByRole('heading',{name:'搭建实验发生的市场'}).waitFor();
 checks.push('browser history navigation');
 for(const width of [1024,390]){
   await page.setViewportSize({width,height:900});
   for(const space of ['Experiment','Agent','Market','Setting']){
     await page.goto(`${base}/studio/${space}`);
     await page.locator('h1').waitFor();
     assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${space} overflow at ${width}`);
     await page.screenshot({path:`qa/${space.toLowerCase()}-${width}.png`,fullPage:true});
   }
 }
 checks.push('1024px and 390px responsive routes without page overflow');
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(`${base}/studio/Experiment`);
 await page.getByRole('heading',{name:'模拟日历'}).waitFor();
 const oldMetrics=await page.locator('.metrics').textContent();
 await page.route('**/api/**',route=>route.abort('failed'));
 await page.getByRole('button',{name:'立即刷新'}).click();
 await page.getByRole('status').filter({hasText:'本地数据连接中断'}).waitFor();
 assert.equal(await page.locator('.metrics').textContent(),oldMetrics);
 await page.screenshot({path:'qa/offline.png'});
 await page.unroute('**/api/**');
 await page.getByRole('button',{name:'立即刷新'}).click();
 await page.getByRole('status').filter({hasText:'本地数据连接中断'}).waitFor({state:'hidden'});
 checks.push('offline preserves snapshot and refresh recovers');
 assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);
 const response=await page.request.post(`${base}/api/runs`,{data:{}});
 assert.equal(response.status(),405);
 checks.push('zero browser write requests, API rejects POST, zero page exceptions');
 console.log(JSON.stringify({passed:true,checks,errors},null,2));
} finally {await browser.close();}
